import * as React from "react"
import { Command as CommandPrimitive } from "cmdk"
import * as DialogPrimitive from "@radix-ui/react-dialog"
import { Search } from "lucide-react"

import { cn } from "@/lib/utils"

/**
 * shadcn/ui `command` primitive — a fast, composable command menu built on
 * `cmdk`. Exposes the building blocks used by the workspace command palette
 * (`CommandPalette.tsx`): `CommandDialog`, `CommandInput`, `CommandList`,
 * `CommandEmpty`, `CommandGroup`, `CommandItem`, `CommandSeparator`, and
 * `CommandShortcut`.
 *
 * `cmdk` provides fuzzy matching + keyboard navigation (arrow/enter) for free;
 * `CommandDialog` wraps everything in a Radix Dialog so the palette is modal,
 * traps focus, and closes on Esc without side effects (VAL-CMDK-006).
 */
function Command({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive>) {
  return (
    <CommandPrimitive
      data-slot="command"
      className={cn(
        "flex h-full w-full flex-col overflow-hidden rounded-md bg-popover text-popover-foreground",
        className
      )}
      {...props}
    />
  )
}

/**
 * Modal command dialog. Reuses Radix Dialog so Esc closes without triggering
 * any item action (VAL-CMDK-006). Pinned near the top of the viewport
 * (Linear-style) instead of vertically centered.
 */
function CommandDialog({
  children,
  open,
  onOpenChange,
}: {
  children: React.ReactNode
  open?: boolean
  onOpenChange?: (open: boolean) => void
}) {
  return (
    <DialogPrimitive.Root open={open} onOpenChange={onOpenChange}>
      <DialogPrimitive.Portal>
        <DialogPrimitive.Overlay
          data-slot="command-overlay"
          className="data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 fixed inset-0 z-50 bg-black/60"
        />
        <DialogPrimitive.Content
          data-slot="command-content"
          className={cn(
            "bg-popover data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95 fixed left-[50%] top-[15vh] z-50 grid w-full max-w-[calc(100%-2rem)] translate-x-[-50%] gap-0 overflow-hidden rounded-lg border border-border p-0 shadow-lg outline-none duration-200 sm:max-w-xl"
          )}
        >
          {/* Accessible name/description for the modal (visually hidden). Radix
              requires a Title so screen readers can announce the dialog. */}
          <DialogPrimitive.Title className="sr-only">
            Command menu
          </DialogPrimitive.Title>
          <DialogPrimitive.Description className="sr-only">
            Search for a page or run a quick action.
          </DialogPrimitive.Description>
          <Command className="[&_[cmdk-group-heading]]:px-2 [&_[cmdk-group-heading]]:py-1.5 [&_[cmdk-group-heading]]:text-xs [&_[cmdk-group-heading]]:font-medium [&_[cmdk-group-heading]]:text-muted-foreground [&_[cmdk-input-wrapper]_svg]:h-4 [&_[cmdk-input-wrapper]_svg]:w-4 [&_[cmdk-input]]:h-12 [&_[cmdk-item]]:px-2 [&_[cmdk-item]]:py-2 [&_[cmdk-item]_svg]:h-4 [&_[cmdk-item]_svg]:w-4">
            {children}
          </Command>
        </DialogPrimitive.Content>
      </DialogPrimitive.Portal>
    </DialogPrimitive.Root>
  )
}

